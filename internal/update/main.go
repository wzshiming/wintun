// Command update replaces embedded/ with the license and DLLs of a Wintun release from https://www.wintun.net,
// mirroring the zip's wintun/ directory, and regenerates version.go, after checking the release zip against the
// SHA-256 published there. The version and SHA-256 are the flags of the //go:generate directive in generate.go.
//
// It writes below the current directory, which is the module root when go generate runs it.
package main

import (
	"archive/zip"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"maps"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"time"
)

// mirrored are the files of the zip's wintun/ directory that embedded/ holds.
var mirrored = []string{"LICENSE.txt", "bin/x86/wintun.dll", "bin/amd64/wintun.dll", "bin/arm64/wintun.dll", "bin/arm/wintun.dll"}

var (
	versionPattern = regexp.MustCompile(`^[0-9]+(\.[0-9]+){1,3}$`)
	sumPattern     = regexp.MustCompile(`^[0-9a-f]{64}$`)
)

func main() {
	version := flag.String("version", "", "Wintun `version` to embed, such as 1.2.3")
	sum := flag.String("sha256", "", "`SHA-256` of wintun-<version>.zip as published on https://www.wintun.net")
	flag.Parse()
	if !versionPattern.MatchString(*version) || !sumPattern.MatchString(*sum) || flag.NArg() != 0 {
		flag.Usage()
		os.Exit(2)
	}
	log.SetFlags(0)
	if err := run(".", "https://www.wintun.net/builds/wintun-"+*version+".zip", *version, *sum); err != nil {
		log.Fatal(err)
	}
}

// run downloads the release zip at url, checks it against sum and writes its files and version below root.
func run(root, url, version, sum string) error {
	data, err := download(url)
	if err != nil {
		return err
	}
	files, err := extract(data, sum)
	if err != nil {
		return fmt.Errorf("%s: %w", url, err)
	}
	if files["version.go"], err = versionFile(version); err != nil {
		return err
	}
	if err := os.RemoveAll(filepath.Join(root, "embedded")); err != nil {
		return err
	}
	for _, name := range slices.Sorted(maps.Keys(files)) {
		path := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, files[name], 0o644); err != nil {
			return err
		}
		fmt.Printf("%x  %s\n", sha256.Sum256(files[name]), name)
	}
	return nil
}

func download(url string) ([]byte, error) {
	client := &http.Client{Timeout: 2 * time.Minute}
	resp, err := client.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", url, resp.Status)
	}
	// A release is under 2 MiB; the limit only stops a runaway response.
	return io.ReadAll(io.LimitReader(resp.Body, 64<<20))
}

// extract checks that the zip data hashes to sum and returns the files to write, by slash-separated path below the module root.
func extract(data []byte, sum string) (map[string][]byte, error) {
	if got := sha256.Sum256(data); hex.EncodeToString(got[:]) != sum {
		return nil, fmt.Errorf("SHA-256 is %x, want %s", got, sum)
	}
	zr, err := zip.NewReader(bytes.NewReader(data), int64(len(data)))
	if err != nil {
		return nil, err
	}
	want := make(map[string]string)
	for _, name := range mirrored {
		want["wintun/"+name] = "embedded/" + name
	}
	files := make(map[string][]byte)
	for _, f := range zr.File {
		name, ok := want[f.Name]
		if !ok {
			continue
		}
		if files[name], err = readZipFile(f); err != nil {
			return nil, fmt.Errorf("%s: %w", f.Name, err)
		}
		delete(want, f.Name)
	}
	if len(want) != 0 {
		return nil, fmt.Errorf("missing %q", slices.Sorted(maps.Keys(want)))
	}
	return files, nil
}

func readZipFile(f *zip.File) ([]byte, error) {
	rc, err := f.Open()
	if err != nil {
		return nil, err
	}
	defer rc.Close()
	return io.ReadAll(rc)
}

func versionFile(version string) ([]byte, error) {
	return format.Source(fmt.Appendf(nil, `// Code generated by go run ./internal/update; DO NOT EDIT.

package wintun

// version is the version of the embedded Wintun DLLs.
const version = %q
`, version))
}
